function out=sr_optimality(z,g,ci,ce,gi,ge,lower,upper,lambda,c)
% Read-only raw-iterate regularity; never relabel recovery multipliers as KKT.
t=tic;fixed=isfinite(lower) & isfinite(upper) & lower==upper;
free=find(~fixed);E=ge(free,:)';nv=numel(z);
stationarity=g+gi*lambda.ineqnonlin+ge*lambda.eqnonlin-lambda.lower+lambda.upper;
out=struct('iterate','exact_raw_optimizer_vector','variables',nv,'equalities',numel(ce), ...
    'fixed_variables',find(fixed)','free_variables',numel(free), ...
    'scaling','existing normalized decision variables; each constraint row divided by its Euclidean norm', ...
    'equality_spectrum',spectrum(E),'raw_stationarity_inf',norm(stationarity,inf), ...
    'fixed_bound_multiplier_uniqueness','individual lower/upper multipliers at equal bounds are nonunique; only their difference is identifiable', ...
    'weaker_constraint_qualifications','not_tested','second_order_sufficiency','not_established', ...
    'physical_infeasibility','unclaimed','kkt_gate_passed',false);
ns=2*c.n*(c.steps+1);out.stationarity_blocks=struct( ...
    'initial_state_inf',norm(stationarity(1:2*c.n),inf), ...
    'other_states_inf',norm(stationarity(2*c.n+1:ns),inf), ...
    'controls_inf',norm(stationarity(ns+1:end-2),inf),'epigraph_inf',norm(stationarity(end-1:end),inf));
rows=cell(3,1);tolerances=[1e-5,1e-7,1e-9];
for k=1:numel(tolerances)
    tol=tolerances(k);task=find(ci>=-tol);
    lo=find(~fixed & isfinite(lower) & z-lower<=tol);
    hi=find(~fixed & isfinite(upper) & upper-z<=tol);
    B=speye(nv);A=[E;gi(free,task)';-B(lo,free);B(hi,free)];
    scale=max(sqrt(sum(A.^2,2)),realmin);S=spdiags(1./scale,0,size(A,1),size(A,1))*A;
    report=spectrum(A);
    if nv>1500
        rows{k}=struct('activity_tolerance',tol,'active_task_indices',task', ...
            'active_lower_indices',lo','active_upper_indices',hi','spectrum',report, ...
            'numerical_LICQ',[],'qualification', ...
            'sparse QR diagonal rank estimate only; numerical LICQ and multiplier sensitivity unresolved');
        continue;
    end
    % Dense work is bounded to the actual saved ~1006-variable problem.
    % SVD/least squares consume a few MB here; no dense matrix is exported.
    rhs=-g(free);mu=lsqminnorm(full(S'),rhs,1e-10);
    direction=sin((1:numel(free))');direction=direction/norm(direction);
    perturbed=lsqminnorm(full(S'),rhs+1e-8*direction,1e-10);
    nEq=size(E,1);dual=mu(nEq+1:end)./scale(nEq+1:end);
    rows{k}=struct('activity_tolerance',tol,'active_task_indices',task', ...
        'active_lower_indices',lo','active_upper_indices',hi','spectrum',report, ...
        'numerical_LICQ',report.rank_at_rtol_1e_9==size(A,1), ...
        'unrestricted_least_squares_stationarity_inf',norm(S'*mu-rhs,inf), ...
        'unrestricted_active_dual_min',min([0;dual]), ...
        'least_squares_multiplier_l2',norm(mu), ...
        'scaled_multiplier_response_per_gradient_perturbation',norm(perturbed-mu)/1e-8, ...
        'qualification','activity and rank depend on declared tolerances; unrestricted least squares is not a dual-feasible multiplier existence test');
end
out.activity_diagnostics=rows;out.elapsed_s=toc(t);
out.reliability='locally_checked_not_certified';

    function result=spectrum(A)
        if size(A,2)>1500
            norms=max(sqrt(sum(A.^2,2)),realmin);
            S=spdiags(1./norms,0,size(A,1),size(A,1))*A;
            R=qr(S',0);diagonal=full(abs(diag(R)));cutoff=max(1e-12,1e-9*max(diagonal));
            result=struct('rows',size(A,1),'columns',size(A,2),'nnz',nnz(A), ...
                'method','sparse QR, no dense matrix or claimed singular spectrum', ...
                'absolute_R_diagonal',diagonal','qr_rank_estimate',sum(diagonal>cutoff), ...
                'qr_cutoff',cutoff,'numerical_rank_certified',false);return;
        end
        raw=svd(full(A),'econ');norms=max(sqrt(sum(A.^2,2)),realmin);
        scaled=svd(full(spdiags(1./norms,0,size(A,1),size(A,1))*A),'econ');
        cutoff=max(1e-12,1e-9*scaled(1));
        result=struct('rows',size(A,1),'columns',size(A,2),'nnz',nnz(A), ...
            'dense_bytes_for_diagnostic',8*numel(A),'raw_extrema',[raw(1),raw(end)], ...
            'row_scaled_singular_values',scaled','row_scaled_condition',scaled(1)/max(realmin,scaled(end)), ...
            'rank_at_rtol_1e_9',sum(scaled>cutoff),'rank_cutoff',cutoff, ...
            'ranks_at_rtol_1e_7_1e_9_1e_11',arrayfun(@(rt)sum(scaled>max(1e-12,rt*scaled(1))),[1e-7,1e-9,1e-11]));
    end
end
